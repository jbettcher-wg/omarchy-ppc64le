#!/usr/bin/env python3
"""Generate omarchy's aqua registry overlay for mise on ppc64le.

mise names ppc64le "powerpc64" and renders aqua's {{.Arch}} that way, so an
aqua recipe with no powerpc64 asset fails there. The overlay replaces mise's
bundled recipe for each package listed below, and only those:

  ARM64   powerpc64 is mapped to whatever the recipe renders for arm64, so mise
          fetches the linux/arm64 build; POWERarm runs it through binfmt_misc.
          arm64-only overrides are copied for powerpc64, and supported_envs that
          admit linux/arm64 also admit linux/powerpc64.
  NATIVE  astral-sh/uv: Astral publishes uv-powerpc64le-unknown-linux-gnu, which
          the stock recipe never names; a linux/powerpc64 override fetches it.

Output is upstream/omarchy-ppc64le-platform/default/mise/aqua-powerpc64.yaml,
which omarchy-settings ships at /usr/share/omarchy/default/mise/ and
etc/mise/conf.d/platform-ppc64le.toml names in aqua.registries.

Regenerate when a recipe changes upstream (a new asset name, a new arch), then
regenerate omarchy-settings' 0001 patch from the platform branch:

    tools/mise-aqua-overlay.py --rev <aqua-registry commit> OUT.yaml

Recipes are fetched from raw.githubusercontent.com at that commit; --recipes DIR
reads <owner>_<name>.yaml files from DIR instead. Needs python-yaml.
"""
import argparse, copy, datetime, pathlib, sys, textwrap, urllib.request
import yaml

ARM64 = [
    "anthropics/claude-code",
    "openai/codex",
    "github/copilot-cli",
    "google-antigravity/antigravity-cli",
    "OpenRouterLabs/ori-releases",
    "earendil-works/pi",
    "modem-dev/hunk",
    "anomalyco/opencode",
]
NATIVE = ["astral-sh/uv"]


def remap_arm64(b, inherited_arm64="arm64"):
    if not isinstance(b, dict):
        return
    repl = b.get("replacements")
    arm = (repl or {}).get("arm64", inherited_arm64)
    if any(k in b for k in ("asset", "url", "replacements", "type")) or repl is not None:
        b.setdefault("replacements", {})
        b["replacements"].setdefault("powerpc64", arm)
    envs = b.get("supported_envs")
    if isinstance(envs, list) and "linux/arm64" in envs and "linux/powerpc64" not in envs:
        envs.append("linux/powerpc64")
    ovs = b.get("overrides")
    if isinstance(ovs, list):
        extra = []
        for o in ovs:
            if isinstance(o, dict) and o.get("goarch") == "arm64":
                c = copy.deepcopy(o)
                c["goarch"] = "powerpc64"
                extra.append(c)
            if isinstance(o, dict) and "replacements" in o:
                o["replacements"].setdefault("powerpc64", o["replacements"].get("arm64", arm))
        ovs.extend(extra)
    for v in b.get("version_overrides", []) or []:
        remap_arm64(v, arm)


def uv_native(p):
    hit = False
    for v in p.get("version_overrides", []) or []:
        if v.get("version_constraint") == "true":
            v.setdefault("overrides", []).append({
                "goos": "linux", "goarch": "powerpc64",
                "replacements": {"powerpc64": "powerpc64le", "linux": "unknown-linux-gnu"},
            })
            hit = True
    if not hit:
        sys.exit("astral-sh/uv: no catch-all version_override; the recipe changed shape, redo uv_native()")


def load(slug, rev, recipes):
    owner, name = slug.split("/")
    if recipes:
        text = (recipes / f"{owner}_{name}.yaml").read_text()
    else:
        url = f"https://raw.githubusercontent.com/aquaproj/aqua-registry/{rev}/pkgs/{owner}/{name}/registry.yaml"
        with urllib.request.urlopen(url, timeout=60) as r:
            text = r.read().decode()
    return yaml.safe_load(text)["packages"]


HEADER = """\
# aqua registry overlay for mise on linux/ppc64le (mise names the arch "powerpc64").
# Each package below replaces mise's bundled aqua recipe of the same name, with
# powerpc64 mapped to whatever the recipe renders for arm64, so mise fetches the
# linux/arm64 build; POWERarm runs it through binfmt_misc. Packages not listed
# here keep mise's bundled recipe. Inert on other arches, but ship it only on
# ppc64le: a frozen copy also freezes the recipe.
#
# Source: aquaproj/aqua-registry @ {rev} ({date}),
#   pkgs/<owner>/<name>/registry.yaml for:
{arm64}
#   astral-sh/uv: NOT remapped to arm64. Astral publishes a native ppc64le build
#   (uv-powerpc64le-unknown-linux-gnu) that the stock recipe never names, so its
#   linux/powerpc64 override fetches that instead.
# Generated by omarchy-ppc64le's tools/mise-aqua-overlay.py --rev {rev}.
# Regenerate whenever one of these recipes changes upstream.

"""


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--rev", required=True, help="aquaproj/aqua-registry commit to read recipes from")
    ap.add_argument("--date", default=datetime.date.today().isoformat(), help="date recorded in the header")
    ap.add_argument("--recipes", type=pathlib.Path, help="read <owner>_<name>.yaml from here instead of fetching")
    ap.add_argument("out", type=pathlib.Path)
    a = ap.parse_args()

    pkgs = []
    for slug in ARM64:
        for p in load(slug, a.rev, a.recipes):
            remap_arm64(p)
            pkgs.append(p)
    for slug in NATIVE:
        for p in load(slug, a.rev, a.recipes):
            uv_native(p)
            pkgs.append(p)

    body = yaml.safe_dump({"packages": pkgs}, sort_keys=False, width=200)
    a.out.write_text(HEADER.format(rev=a.rev, date=a.date, arm64=textwrap.fill(" ".join(ARM64), 88, initial_indent="#   ", subsequent_indent="#   ", break_on_hyphens=False)) + body)
    print(f"{len(pkgs)} package(s) -> {a.out}")


if __name__ == "__main__":
    main()
